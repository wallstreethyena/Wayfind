#!/usr/bin/env node
// Compiles data/social/wayfind-instagram.json (Wayfind's own Instagram
// inventory, synced from Metricool) into lib/wayfindSocialAssets.generated.js,
// so server code imports it without a JSON import attribute.
//   node scripts/gen-wayfind-social.mjs          write
//   node scripts/gen-wayfind-social.mjs --check  exit 1 if the file is stale
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const SRC = new URL("../data/social/wayfind-instagram.json", import.meta.url);
const OUT = new URL("../lib/wayfindSocialAssets.generated.js", import.meta.url);

export function renderWayfindSocial(data) {
  const keep = (a) => ({
    id: a.id, permalink: a.permalink, format: a.format, published_at: a.published_at,
    caption: a.caption || "", metrics: a.metrics || {}, kind: a.kind, kind_reason: a.kind_reason || null,
    twin_of: a.twin_of || null, entities: (a.entities || []).map((e) => ({ type: e.type, id: e.id })),
    city: a.city || null, seasons: a.seasons || [],
  });
  const body = { source: data.source, synced_at: data.synced_at, assets: (data.assets || []).map(keep) };
  return "// GENERATED by scripts/gen-wayfind-social.mjs from data/social/wayfind-instagram.json. Do not edit.\n"
    + "// Server only (lib/socialAssets.js). Wayfind's own @gowayfind.app posts.\n"
    + "export const WAYFIND_SOCIAL = Object.freeze(" + JSON.stringify(body) + ");\n";
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  const want = renderWayfindSocial(JSON.parse(readFileSync(SRC, "utf8")));
  if (process.argv.includes("--check")) {
    const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (have !== want) { console.error("gen-wayfind-social: STALE — run node scripts/gen-wayfind-social.mjs"); process.exit(1); }
    // And the module the server actually imports carries every inventory post.
    const { WAYFIND_SOCIAL } = await import("../lib/wayfindSocialAssets.generated.js");
    const src = JSON.parse(readFileSync(SRC, "utf8")).assets || [];
    const got = new Set((WAYFIND_SOCIAL.assets || []).map((a) => a.permalink));
    const lost = src.filter((a) => !got.has(a.permalink));
    if (!src.length || lost.length) { console.error(`gen-wayfind-social: FAIL — ${lost.length} of ${src.length} inventory posts are not in the imported module`); process.exit(1); }
    console.log(`gen-wayfind-social: OK — generated file matches the inventory; the imported module carries all ${src.length} posts`);
  } else {
    writeFileSync(OUT, want);
    console.log("gen-wayfind-social: wrote lib/wayfindSocialAssets.generated.js");
  }
}
