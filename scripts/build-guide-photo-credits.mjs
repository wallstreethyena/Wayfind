#!/usr/bin/env node
/**
 * build-guide-photo-credits — regenerates public/guides/picks/CREDITS.md from
 * every photo record (picks and hero) in data/guide-pick-photos/*.json.
 *
 * public/guides/CREDITS.md already credits one hero image per guide slug.
 * data/guide-pick-photos adds a second layer this project had no attribution
 * file for: the per-pick photos (restaurant/venue fronts, etc.) that ship
 * under public/guides/picks/<slug>/. Every one of those is a Creative Commons
 * download and needs the same author/licence trail the hero images get.
 *
 * Deterministic and regenerable: sorted by guide slug, then by pick name
 * (hero last within a guide), with no timestamp or other run-to-run noise in
 * the output — a rerun with no data change produces byte-identical output.
 *
 * Usage: node scripts/build-guide-photo-credits.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const dataDir = path.join(repoRoot, "data/guide-pick-photos");
const outputPath = path.join(repoRoot, "public/guides/picks/CREDITS.md");

const files = fs
  .readdirSync(dataDir)
  .filter((f) => f.endsWith(".json"))
  .sort((a, b) => a.localeCompare(b));

if (files.length === 0) {
  throw new Error(`no data/guide-pick-photos/*.json files found under ${dataDir}`);
}

/** @param {Record<string, string>} rec */
function creditLine(rec) {
  const parts = [`[${rec.author}](${rec.creditHref})`, `[${rec.license}](${rec.licenseUrl})`];
  let line = parts.join("; ") + ".";
  if (rec.license.startsWith("CC BY-SA")) {
    line += " Adaptation (resized, cropped, WebP) released under the same licence.";
  }
  return line;
}

const sections = [];
let photoCount = 0;

for (const file of files) {
  const raw = fs.readFileSync(path.join(dataDir, file), "utf8");
  const data = JSON.parse(raw);
  const slug = data.slug || path.basename(file, ".json");

  const picks = Object.entries(data.picks || {}).sort(([a], [b]) => a.localeCompare(b));
  const rows = [];
  for (const [pickName, rec] of picks) {
    rows.push(`- \`${rec.src}\` — ${slug}: ${pickName}. ${creditLine(rec)}`);
    photoCount++;
  }
  if (data.hero) {
    rows.push(`- \`${data.hero.src}\` — ${slug}: hero image. ${creditLine(data.hero)}`);
    photoCount++;
  }

  if (rows.length === 0) continue; // guide has only unfulfilled gaps, no photo to credit
  sections.push(`## ${slug}\n\n${rows.join("\n")}`);
}

const header = [
  "# Guide pick photo credits",
  "",
  "Generated by `scripts/build-guide-photo-credits.mjs` from every `data/guide-pick-photos/*.json`" +
    " record (picks and hero). Do not hand-edit — rerun the script after any data file changes:" +
    " `node scripts/build-guide-photo-credits.mjs`.",
  "",
  "Each photo uses the license named below; images may be resized, cropped and converted to WebP" +
    " for display. A CC BY-SA source keeps its adaptation under the same licence, noted per entry below.",
].join("\n");

const body = sections.join("\n\n");
const output = `${header}\n\n${body}\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);
console.log(`wrote ${outputPath} (${photoCount} photo credits across ${sections.length} guides)`);
