#!/usr/bin/env node
// scripts/emit-cuisine-sql.mjs — GENERATE the backfill SQL from lib/cuisine.js.
//
// WHY GENERATED AND NOT HAND-WRITTEN. The classifier has to exist in JS (the cron
// runs it per row) and the one-time backfill has to run in SQL (Supabase's legacy
// REST keys were disabled 2026-07-16, so the batch path over ~1,100 rows is a
// query, not a fetch loop). Two hand-maintained copies of thirty regexes would
// drift within a week, and the drift would be invisible: both sides would run,
// neither would error, and a cuisine would quietly stop matching in one of them.
//
// So the JS module is the single source of truth and the SQL is emitted from it.
// scripts/check-cuisine-sql-in-sync.mjs regenerates and diffs, so a change to the
// regexes that is not reflected in the migration fails the build.
//
//   node scripts/emit-cuisine-sql.mjs > supabase/migrations/<n>_cuisine_backfill.sql
import { TYPE_CUISINE, NAME_CUISINE, NAME_VETO } from "../lib/cuisine.js";

// JS regex -> POSIX ERE. \b has no POSIX equivalent; Postgres spells it \y.
// Everything else in these patterns (alternation, groups, ?, character classes)
// is already compatible. Asserted, not assumed: the guard re-emits and compares.
const pg = (rx) => rx.source.replace(/\\b/g, "\\y").replace(/'/g, "''");

const GENERIC = ["asian", "latin-american", "american", "mediterranean", "caribbean"];

const lines = [];
lines.push(`-- GENERATED by scripts/emit-cuisine-sql.mjs from lib/cuisine.js — DO NOT EDIT BY HAND.`);
lines.push(`-- Regenerate: node scripts/emit-cuisine-sql.mjs > this file`);
lines.push(`-- check-cuisine-sql-in-sync.mjs fails the build if this drifts from the module.`);
lines.push(`--`);
lines.push(`-- Backfills wf_inventory.cuisines for every food row using signals we ALREADY`);
lines.push(`-- hold: google_types[], the name, and wf_editorial prose. No API calls.`);
lines.push(`--`);
lines.push(`-- THE RULE: these are FILTER labels over local inventory, never query terms.`);
lines.push(``);
lines.push(`with ed as (`);
lines.push(`  select place_id, lower(coalesce(hook,'') || ' ' || coalesce(why_here,'')) as txt`);
lines.push(`  from public.wf_editorial`);
lines.push(`),`);
lines.push(`src as (`);
lines.push(`  select i.place_id, lower(i.name) as nm, coalesce(i.google_types,'{}') as tys,`);
lines.push(`         coalesce(ed.txt,'') as edtxt`);
lines.push(`  from public.wf_inventory i left join ed on ed.place_id = i.place_id`);
lines.push(`  where i.category = 'food'`);
lines.push(`),`);
// Vetoes: a row that trips a "*" veto gets no cuisine at all.
const starVetoes = NAME_VETO.filter((v) => v.blocks.includes("*"));
const scopedVetoes = NAME_VETO.filter((v) => !v.blocks.includes("*"));
lines.push(`vetoed as (`);
lines.push(`  select place_id from src where`);
lines.push(
  starVetoes
    .map((v) => `    (nm ~* '${pg(v.rx)}'${v.unless ? ` and nm !~* '${pg(v.unless)}'` : ""})   -- ${v.why}`)
    .join("\n    or\n")
);
lines.push(`),`);
// Per-cuisine evidence, one row per (place, cuisine, confidence).
lines.push(`-- Signal tables, emitted as VALUES so thirty regexes are one relation`);
lines.push(`-- instead of thirty unioned SELECTs.`);
lines.push(`type_map(ty, cuisine) as (values`);
lines.push(Object.entries(TYPE_CUISINE).map(([t, c]) => `  ('${t}','${c}')`).join(",\n"));
lines.push(`),`);
lines.push(`name_map(cuisine, rx) as (values`);
lines.push(NAME_CUISINE.map(({ cuisine, rx }) => `  ('${cuisine}','${pg(rx)}')`).join(",\n"));
lines.push(`),`);
// Scoped vetoes block ONE cuisine rather than the whole row (the Kobe case).
lines.push(`scoped_veto(cuisine, rx, unless_rx) as (values`);
lines.push(
  (scopedVetoes.length
    ? scopedVetoes.flatMap((v) => v.blocks.map((b) => `  ('${b}','${pg(v.rx)}',${v.unless ? `'${pg(v.unless)}'` : "null"})`))
    : ["  (null::text, null::text, null::text)"]
  ).join(",\n")
);
lines.push(`),`);
lines.push(`hits as (`);
lines.push(`  select s.place_id, tm.cuisine, 0.90::numeric as conf, 'google-types'::text as src`);
lines.push(`    from src s join type_map tm on tm.ty = any(s.tys)`);
lines.push(`  union all`);
lines.push(`  select s.place_id, nm2.cuisine, 0.70::numeric, 'name'::text`);
lines.push(`    from src s join name_map nm2 on s.nm ~* nm2.rx`);
lines.push(`  union all`);
lines.push(`  select s.place_id, nm2.cuisine, 0.55::numeric, 'editorial'::text`);
lines.push(`    from src s join name_map nm2 on s.edtxt <> '' and s.edtxt ~* nm2.rx`);
lines.push(`),`);
lines.push(`live as (`);
lines.push(`  select h.* from hits h`);
lines.push(`  join src s on s.place_id = h.place_id`);
lines.push(`  where h.place_id not in (select place_id from vetoed)`);
lines.push(`    and not exists (`);
lines.push(`      select 1 from scoped_veto sv`);
lines.push(`      where sv.cuisine = h.cuisine and s.nm ~* sv.rx`);
lines.push(`        and (sv.unless_rx is null or s.nm !~* sv.unless_rx))`);
lines.push(`),`);
// Specific beats generic: knowing a place is korean is worth more than "asian".
lines.push(`ranked as (`);
lines.push(`  select place_id, cuisine, max(conf) as conf,`);
lines.push(`         bool_or(cuisine <> all(array[${GENERIC.map((g) => `'${g}'`).join(",")}])) over (partition by place_id) as has_specific`);
lines.push(`  from live group by place_id, cuisine`);
lines.push(`),`);
lines.push(`kept as (`);
lines.push(`  select place_id, cuisine, conf from ranked`);
lines.push(`  where has_specific = false or cuisine <> all(array[${GENERIC.map((g) => `'${g}'`).join(",")}])`);
lines.push(`),`);
lines.push(`agg as (`);
lines.push(`  select k.place_id,`);
lines.push(`         array_agg(k.cuisine order by k.conf desc, k.cuisine) as cuisines,`);
lines.push(`         max(k.conf) as conf,`);
lines.push(`         (select array_agg(distinct l.src order by l.src) from live l where l.place_id = k.place_id) as srcs`);
lines.push(`  from kept k group by k.place_id`);
lines.push(`)`);
lines.push(`update public.wf_inventory i set`);
lines.push(`  cuisines           = coalesce(a.cuisines, '{}'),`);
lines.push(`  cuisine_confidence = a.conf,`);
lines.push(`  cuisine_sources    = coalesce(a.srcs, case when v.place_id is not null then array['name-veto'] else '{}' end),`);
lines.push(`  cuisine_reason     = case`);
lines.push(`                         when v.place_id is not null then 'vetoed: not a cuisine-bearing restaurant'`);
lines.push(`                         when a.place_id is null then 'unclassifiable'`);
lines.push(`                         else 'classified' end,`);
lines.push(`  cuisine_checked_at = now()`);
lines.push(`from src s`);
lines.push(`  left join agg a on a.place_id = s.place_id`);
lines.push(`  left join vetoed v on v.place_id = s.place_id`);
lines.push(`where i.place_id = s.place_id;`);

console.log(lines.join("\n"));
