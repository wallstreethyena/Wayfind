import assert from "node:assert/strict";
import { seasonalHospitalityEligible, seasonalHospitalityIds, seasonalHospitalityPlaces, mergeSeasonalHospitalityPlaces, reconcileSeasonalHospitalityEvents } from "../lib/seasonalHospitality.js";
import { composeFallIntentRails } from "../lib/fallIntentRails.js";
import { composeHalloweenRails } from "../lib/halloweenIntentRails.js";
import { composeChristmasIntentRails } from "../lib/christmasIntentRails.js";
const today = "2026-10-18";
const claim = { name: "Nightmare at Test Bar", city: "Tampa", place_id: "fixture-bar", status: "confirmed_2026", experience: "decorated_bar", season: ["halloween"], source_url: "https://example.com/halloween-2026", offering: "Halloween rooms and themed cocktails.", checked_at: today, start_date: "2026-10-23", end_date: "2026-10-31", occurrence_dates: [] };
const inventory = { place_id: "fixture-bar", name: "Test Bar", lat: 27.95, lng: -82.46, status: "OPERATIONAL", photo_url: "/fixture-owned-bar.jpg", signals: { rating: 4.8, reviews: 300 } };
assert.equal(seasonalHospitalityEligible(claim, "halloween", today), true);
for (const patch of [{status:"pending_2026"},{status:"excluded"},{experience:"folklore"},{place_id:null},{source_url:""},{checked_at:"2026-10-19"},{end_date:"2026-10-17"},{occurrence_dates:["2026-10-17"]},{start_date:"2026-11-01",end_date:"2026-10-31"},{start_date:"2026-02-30"},{occurrence_dates:["2026-10-32"]}]) assert.equal(seasonalHospitalityEligible({...claim,...patch},"halloween",today),false,JSON.stringify(patch));
assert.equal(seasonalHospitalityEligible(claim,"christmas",today),false);
assert.equal(seasonalHospitalityEligible(claim,"halloween","2027-10-18"),false);
assert.deepEqual(seasonalHospitalityIds("halloween",today,[claim,claim]),["fixture-bar"]);
const projected = seasonalHospitalityPlaces([inventory],"halloween",today,[claim]);
assert.equal(projected.length,1);
assert.equal(projected[0].halloweenRail,"decorated-bars");
assert.match(projected[0].seasonalWhen,/2026-10-23/);
assert.equal(projected[0].hospitalityEvidence.sourceUrl,claim.source_url);
assert.equal(projected[0].id,inventory.place_id);
assert.ok(projected[0].wfScore > 0);
assert.equal(seasonalHospitalityPlaces([{...inventory,signals:{}}],"halloween",today,[claim])[0].wfScore,null);
for (const patch of [{excluded:true},{status:"CLOSED_PERMANENTLY"},{lat:null},{photo_url:null}]) assert.equal(seasonalHospitalityPlaces([{...inventory,...patch}],"halloween",today,[claim]).length,0);
assert.equal(seasonalHospitalityPlaces([],"halloween",today,[claim]).length,0);
assert.equal(mergeSeasonalHospitalityPlaces([{id:"fixture-bar",take:"ordinary"}],projected).length,1);
const fall=composeFallIntentRails([],projected,{lat:27.95,lng:-82.46,today});
const halloween=composeHalloweenRails(fall.rails,today);
assert.equal(halloween.find(r=>r.id==="decorated-bars").cards.length,1);
assert.equal(halloween.find(r=>r.id==="last-minute").cards.length,0);
const far=composeFallIntentRails([],projected,{lat:25.76,lng:-80.19,today});
assert.equal(far.rails.flatMap(r=>r.cards).length,0);
const xmas={...claim,season:["christmas"],start_date:null,end_date:null};
const xmasPlaces=seasonalHospitalityPlaces([inventory],"christmas",today,[xmas]);
assert.equal(xmasPlaces[0].seasonalWhen,"2026 season confirmed; dates pending");
assert.equal(composeChristmasIntentRails([],xmasPlaces,{lat:27.95,lng:-82.46,today}).rails.find(r=>r.id==="popup-bars").cards.length,1);
assert.equal(seasonalHospitalityPlaces([inventory],"christmas","2027-01-07",[xmas]).length,0);


assert.equal(seasonalHospitalityEligible({...claim,season:["christmas"]},"christmas",today),false);
const event={id:"nightmare-event",place_id:claim.place_id,title:claim.name,start_date:"2026-09-22",end_date:"2026-11-01"};
const reconciled=reconcileSeasonalHospitalityEvents([event,{...event,id:"separate-party",title:"Costume dance night"}],projected);
assert.equal(reconciled.events.length,2);
assert.equal(reconciled.places.length,0);
assert.equal(reconciled.events[0].start_date,"2026-09-22");
assert.equal(reconciled.events[0].halloweenRail,"decorated-bars");
assert.equal(reconciled.events[1].hospitalityEvidence,undefined);
assert.equal(projected[0].select_nights,true);

const separateParty={...event,title:"Halloween Costume Party at Nightmare at Test Bar",url:claim.source_url};
assert.equal(reconcileSeasonalHospitalityEvents([separateParty],projected).places.length,1);
assert.equal(reconcileSeasonalHospitalityEvents([{...event,title:"Other outing",url:"https://example.com/"}],[{...projected[0],sourceUrl:"https://example.com/"}]).places.length,1);
const christmasEvent={...event,title:claim.name,tags:["christmas"],subcategory:"christmas"};
const christmasReconciled=reconcileSeasonalHospitalityEvents([christmasEvent],xmasPlaces);
assert.equal(christmasReconciled.events[0].christmas_rail,"popup-bars");
