import assert from "node:assert/strict";
import { thanksgivingWindow, validThanksgivingDate, thanksgivingYearForDate, thanksgivingScopeKey } from "../lib/thanksgivingDates.js";
import { activeHoliday } from "../lib/holidays.js";
import { siteTodayStr, utcCalendarDateKey } from "../lib/siteTime.js";
import { validThanksgivingRadius } from "../lib/thanksgivingRadius.js";

assert.deepEqual(thanksgivingWindow(2026).days, ["2026-11-26", "2026-11-27", "2026-11-28", "2026-11-29"]);
assert.deepEqual(thanksgivingWindow(2024).days, ["2024-11-28", "2024-11-29", "2024-11-30", "2024-12-01"]);
assert.equal(thanksgivingWindow(2027).start, "2027-11-25");
assert.equal(thanksgivingWindow(2026).label, "Nov 26 to Nov 29, 2026");
assert.equal(activeHoliday(new Date(2026, 10, 27, 12)).key, "thanksgiving");
assert.equal(activeHoliday(new Date(2026, 10, 29, 23, 59, 59, 999)).key, "thanksgiving");
assert.equal(activeHoliday(new Date(2026, 10, 30, 0)).key, "christmas");
assert.equal(activeHoliday(new Date(2024, 11, 1, 18)).key, "thanksgiving");
assert.equal(activeHoliday(new Date(2024, 11, 2, 0)).key, "christmas");
assert.equal(thanksgivingYearForDate("2026-11-29"), 2026);
assert.equal(thanksgivingYearForDate("2026-11-30"), 2027);
assert.equal(thanksgivingYearForDate("2024-12-01"), 2024);
assert.equal(thanksgivingYearForDate("2024-12-02"), 2025);
assert.equal(thanksgivingYearForDate(siteTodayStr(new Date("2026-11-30T02:00:00Z"))), 2026);
assert.equal(thanksgivingYearForDate(siteTodayStr(new Date("2026-11-30T05:00:00Z"))), 2027);
assert.equal(utcCalendarDateKey(Date.UTC(2024, 11, 1)), "2024-12-01");
assert.throws(() => utcCalendarDateKey(), RangeError);
assert.equal(validThanksgivingDate(2026, "2026-11-27"), true);
assert.equal(validThanksgivingDate(2026, "2026-11-30"), false);
assert.equal(validThanksgivingDate(2026, "2027-11-25"), false);
assert.equal(validThanksgivingDate("oops", "all"), false);
assert.throws(() => thanksgivingYearForDate("2026-02-30"), RangeError);
assert.throws(() => thanksgivingWindow(2026.5), RangeError);
assert.throws(() => thanksgivingWindow(2101), RangeError);
const scope = { lat: 27.58, lng: -82.42, year: 2026, mi: 60, date: "all" };
const key = thanksgivingScopeKey(scope);
assert.notEqual(key, thanksgivingScopeKey({ ...scope, lat: 27.59 }));
assert.notEqual(key, thanksgivingScopeKey({ ...scope, lng: -82.43 }));
assert.notEqual(key, thanksgivingScopeKey({ ...scope, year: 2027 }));
assert.notEqual(key, thanksgivingScopeKey({ ...scope, mi: 30 }));
assert.notEqual(key, thanksgivingScopeKey({ ...scope, date: "2026-11-26" }));
assert.throws(() => thanksgivingScopeKey({ ...scope, date: "2026-11-30" }), RangeError);
assert.throws(() => thanksgivingScopeKey({ ...scope, lat: NaN }), RangeError);
assert.throws(() => thanksgivingScopeKey({ ...scope, mi: 0 }), RangeError);
assert.deepEqual([1, 15, 30, 45, 60, "17"].map(validThanksgivingRadius), [true, true, true, true, true, true]);
assert.deepEqual([undefined, null, "", " ", NaN, Infinity, 0, 61, 120, 1.5, true, {}, []].map(validThanksgivingRadius), Array(13).fill(false));
assert.equal(thanksgivingScopeKey({ ...scope, mi: 1 }).split("|").at(-2), "1");
assert.equal(thanksgivingScopeKey({ ...scope, mi: "17" }).split("|").at(-2), "17");
assert.throws(() => thanksgivingScopeKey({ ...scope, mi: 61 }), RangeError);
assert.throws(() => thanksgivingScopeKey({ ...scope, mi: 1.5 }), RangeError);
assert.throws(() => thanksgivingScopeKey({ ...scope, mi: null }), RangeError);
assert.throws(() => thanksgivingScopeKey({ ...scope, mi: " " }), RangeError);
console.log("Thanksgiving dates: recurrence, December rollover, weekend promotion, and request identity passed.");
