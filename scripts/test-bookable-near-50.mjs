import assert from 'node:assert/strict';
import path from 'node:path';
import { experienceWayfindScore } from '../lib/experiencesData.js';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { loadComponent } from './lib/jsxLoad.mjs';
import { resolveBrowseExperienceRows, shouldLiveSearchFallback } from '../lib/browseExperienceLanes.js';
const root = process.cwd();
const { default: Rail, BOOKABLE_NEAR_LIMIT } = await loadComponent(path.join(root, 'app/components/UnifiedBrowseCommerceRail.js'), root);
const rows = Array.from({length:80}, (_, i) => ({ code:`123P${i+1}`, title:`Family aquarium admission ${i}`, categories:['theme'], image:`https://example.com/${i}.jpg`, rating:4.5+i/200, reviews:1000 }));
const render = (props={}) => renderToStaticMarkup(createElement(Rail, {cat:'family',sub:'all',lat:27.944,lng:-82.445,city:'Tampa',initialExperiences:rows,...props}));
const html=render();
assert.equal(BOOKABLE_NEAR_LIMIT,50);
assert.equal((html.match(/rel="sponsored nofollow noopener"/g)||[]).length,50);
assert.match(html,/50 options/);
const renderedIds = [...html.matchAll(/>Family aquarium admission (\d+)<\/div>/g)].map(m=>Number(m[1]));
assert.equal(renderedIds.length,50);
const scores=renderedIds.map(i=>experienceWayfindScore(rows[i]));
assert.ok(scores.every((n,i)=>!i||scores[i-1]>=n),'visible scores descend');
assert.ok(scores.at(-1)>=experienceWayfindScore(rows[0]),'best scores fill the cap');
assert.match(html,/loading="lazy"/);
assert.match(html,/browse_partner_rail/);
const filtered=render({initialExperiences:[rows[0],{...rows[0],code:'999P2'}, {...rows[1],link_ok:false},{...rows[2],image:''},{...rows[3],title:'Adults only shooting experience'}]});
assert.equal((filtered.match(/rel="sponsored nofollow noopener"/g)||[]).length,1,'duplicate, dead, imageless and unsafe offers excluded');
assert.equal(render({cat:'food'}),'');
assert.equal(render({sub:'rainy',initialExperiences:[{...rows[0],title:'Family outdoor boat cruise'}]}),'');
const pin={id:'test-aquarium',name:'The Florida Aquarium',lat:27.944,lng:-82.445,rating:4.7,reviews:3000,types:['aquarium'],photo:'https://example.com/aquarium.jpg'};
assert.match(render({initialExperiences:[],places:[pin]}),/Florida Aquarium/,'exact nearby Klook pin is rendered');
assert.equal(render({initialExperiences:[],places:[{...pin,lat:40}]}),'','faraway pin excluded');
assert.equal(render({initialExperiences:[],places:[{...pin,name:'Unverified Aquarium'}]}),'','unknown pin excluded');
assert.deepEqual(resolveBrowseExperienceRows({includeExperiences:true,initialExperiences:[],cachedRows:[rows[0]]}),[rows[0]],'empty parent still admits cached inventory');
assert.equal(shouldLiveSearchFallback({includeExperiences:true,initialExperiences:null,cachedCount:0}),false,'parent owned fetch is not duplicated');
assert.equal(shouldLiveSearchFallback({includeExperiences:true,initialExperiences:undefined,cachedCount:0}),true);
console.log('Bookable near 50: actual component cap, score order, links, matching, dedupe and geography OK');
