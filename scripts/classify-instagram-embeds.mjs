#!/usr/bin/env node
// scripts/classify-instagram-embeds.mjs — records, for every Instagram post Wayfind
// links to, whether Instagram's OFFICIAL embed plays it inside our page.
//
// Owner 2026-11-20: "When i click here it took me to instagram. I want all of
// these to play inside gowayfind. Do not send the user to Instagram."
//
// Instagram decides per post. For some reels (often ones with licensed music)
// its embed carries no video at all, only a "Watch on Instagram" link that
// leaves Wayfind. Those posts are recorded "handoff" and lib/videoEmbed.js
// gives them no player, so no surface shows a play button that sends a visitor
// away. Nothing is downloaded, copied or rehosted; this only reads the public
// embed page Instagram itself serves for embedding.
//
// Verdicts (lib/instagramEmbedVerdicts.js, two shortcode lists):
//   inline   the embed carries the video (or is a photo / carousel post)
//   handoff  the embed carries only Instagram's "Watch on Instagram" link
// A page that does not look like that post's embed (login wall, rate limit,
// deleted post) records nothing and is reported, so a bad fetch never
// becomes a verdict. Unknown posts get no player (fail closed).
//
// Usage: node scripts/classify-instagram-embeds.mjs            only new posts
//        node scripts/classify-instagram-embeds.mjs --recheck  every post
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { siteTodayStr } from "../lib/siteTime.js";

const ROOT = new URL("..", import.meta.url).pathname;
const OUT = join(ROOT, "lib/instagramEmbedVerdicts.js");
const UA = "WayfindBot/1.0 (https://gowayfind.com)";
const RE = /instagram\.com\/(reel|reels|p|tv)\/([A-Za-z0-9_-]+)/g;

export function collectShortcodes(root = ROOT) {
  const found = new Map();
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      if (name === "node_modules" || name.startsWith(".")) continue;
      const p = join(dir, name);
      const st = statSync(p);
      if (st.isDirectory()) walk(p);
      else if (/\.(m?js|jsx|json)$/.test(name) && !p.endsWith("instagramEmbedVerdicts.js")) {
        const src = readFileSync(p, "utf8");
        for (const m of src.matchAll(RE)) if (!found.has(m[2])) found.set(m[2], m[1] === "reels" ? "reel" : m[1]);
      }
    }
  };
  walk(join(root, "lib"));
  walk(join(root, "app"));
  return found;
}

export function verdictFromEmbedHtml(html, shortcode) {
  const s = String(html || "");
  if (!s.includes(shortcode) || !/EmbeddedMedia|EmbedVideo|Embed\b/.test(s)) return null;
  if (/video_url|\.mp4/.test(s)) return "inline";
  if (/Watch on Instagram/.test(s)) return "handoff";
  return "inline";
}

async function main() {
  const recheck = process.argv.includes("--recheck");
  const data = { verdicts: {} };
  try {
    const mod = await import(OUT + "?t=" + Date.now());
    for (const c of mod.INSTAGRAM_INLINE.split(" ").filter(Boolean)) data.verdicts[c] = "inline";
    for (const c of mod.INSTAGRAM_HANDOFF.split(" ").filter(Boolean)) data.verdicts[c] = "handoff";
  } catch {}
  const all = collectShortcodes();
  const todo = [...all].filter(([code]) => recheck || !data.verdicts[code]);
  const failed = [];
  let n = 0;
  for (const [code, kind] of todo) {
    n++;
    try {
      const res = await fetch(`https://www.instagram.com/${kind}/${code}/embed/`, { headers: { "User-Agent": UA } });
      const v = res.ok ? verdictFromEmbedHtml(await res.text(), code) : null;
      if (v) data.verdicts[code] = v; else failed.push(code);
    } catch { failed.push(code); }
    if (n % 25 === 0) process.stdout.write(`  ${n}/${todo.length}\n`);
    await new Promise((r) => setTimeout(r, 400));
  }
  const sorted = Object.fromEntries(Object.entries(data.verdicts).sort(([a], [b]) => a.localeCompare(b)));
  const list = (v) => Object.keys(sorted).filter((c) => sorted[c] === v).join(" ");
  writeFileSync(OUT, [
    "// GENERATED by scripts/classify-instagram-embeds.mjs. Do not hand edit; rerun the script.",
    "// Which Instagram posts Instagram's official embed plays inside Wayfind (owner 2026-11-20).",
    `export const INSTAGRAM_VERDICTS_CHECKED = ${JSON.stringify(siteTodayStr())};`,
    `export const INSTAGRAM_INLINE = ${JSON.stringify(list("inline"))};`,
    `export const INSTAGRAM_HANDOFF = ${JSON.stringify(list("handoff"))};`,
    "",
  ].join("\n"));
  const counts = Object.values(sorted).reduce((m, v) => ((m[v] = (m[v] || 0) + 1), m), {});
  console.log(`classify-instagram-embeds: ${todo.length} fetched, ${all.size} posts in source, verdicts ${JSON.stringify(counts)}, unresolved ${failed.length}${failed.length ? ": " + failed.slice(0, 20).join(" ") : ""}`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
