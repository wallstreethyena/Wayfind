#!/usr/bin/env node
// scripts/build-guide-pick-photos.mjs — GENERATOR for lib/guidePickPhotoManifest.js.
//
// Source of truth: one file per guide under data/guide-pick-photos/<slug>.json,
// shaped { slug, picks: { "<exact pick name>": ENTRY }, hero?: ENTRY, gaps?:
// { "<pick name>": {reason, placeId, needsPermissionFrom, note} } } — see
// scripts/check-guide-pick-photos.mjs for the full ENTRY contract and every
// assertion this data must pass.
//
// Run this by hand after adding or editing a data/guide-pick-photos/*.json
// file, and commit the regenerated lib/guidePickPhotoManifest.js alongside it:
//
//   node scripts/build-guide-pick-photos.mjs
//
// WHY A SEPARATE GENERATED FILE rather than reading the JSON directory at
// request time: lib/guidePickPhotoManifest.js is a plain ES module a server
// component can statically import — no readdirSync/readFileSync at request
// time, no filesystem access needed on Vercel's serverless runtime, and the
// exact same "generated file must be in sync with its source" discipline
// scripts/lib/build-guard-registry.mjs already established for
// scripts/lib/guard-registry.json (this file mirrors that split: the pure
// DERIVATION lives in the exported functions below, so both this generator
// and the guard call the identical logic instead of two hand-synced copies).
//
// `gaps` is intentionally NOT copied into the generated manifest — it is
// documentation of picks with NO photo yet (why, and what would unblock it),
// never something the app renders. scripts/check-guide-pick-photos.mjs reads
// the JSON files directly to validate it.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const DATA_DIR = path.join(ROOT, "data/guide-pick-photos");
export const OUT_PATH = path.join(ROOT, "lib/guidePickPhotoManifest.js");
export const CARD_INDEX_PATH = path.join(ROOT, "lib/guideCardPhotoIndex.js");

/** Every data/guide-pick-photos/*.json file, parsed, sorted by filename. */
export function loadGuidePickPhotoFiles(dataDir = DATA_DIR) {
  let names;
  try {
    names = readdirSync(dataDir).filter((f) => f.endsWith(".json"));
  } catch {
    names = [];
  }
  return names.sort().map((name) => {
    const raw = readFileSync(path.join(dataDir, name), "utf8");
    let json;
    try {
      json = JSON.parse(raw);
    } catch (e) {
      throw new Error(`${name}: invalid JSON (${e.message})`);
    }
    return { file: name, json };
  });
}

/**
 * Pure derivation, no I/O beyond the file list already handed in — DETERMINISTIC:
 * same input files always produce the same output object (slugs sorted, pick
 * names within each guide sorted), so two agents adding data files in either
 * order regenerate byte-identical output, and the "manifest in sync with the
 * JSON files" guard check is a plain deep-equality comparison.
 */
export function buildGuidePickPhotos(files) {
  const bySlug = {};
  for (const { file, json } of files) {
    if (!json || typeof json !== "object" || typeof json.slug !== "string" || !json.slug) {
      throw new Error(`${file}: missing "slug"`);
    }
    if (Object.hasOwn(bySlug, json.slug)) {
      throw new Error(`duplicate slug "${json.slug}" — already produced by another data file`);
    }
    const picks = {};
    for (const name of Object.keys(json.picks || {}).sort()) picks[name] = json.picks[name];
    const entry = { picks };
    if (json.hero) entry.hero = json.hero;
    bySlug[json.slug] = entry;
  }
  const sorted = {};
  for (const slug of Object.keys(bySlug).sort()) sorted[slug] = bySlug[slug];
  return sorted;
}

export function renderManifestSource(data) {
  return `// GENERATED by scripts/build-guide-pick-photos.mjs — do not hand-edit.
// Source of truth: data/guide-pick-photos/*.json (one file per guide).
// Run \`node scripts/build-guide-pick-photos.mjs\` after adding or editing a
// pick-photo data file, and commit this file in the same change — see
// scripts/check-guide-pick-photos.mjs, which fails the build when this file
// disagrees with the JSON it was derived from.
export const GUIDE_PICK_PHOTOS = ${JSON.stringify(data, null, 2)};
`;
}

/**
 * Tiny index for the CLIENT-side guide card (app/components/GuideDiscoveryCard.js):
 * slug -> { hero, pick } with only {src, credit, href, position[, kind]}. The full
 * manifest is ~330KB and guideHero.js ~70KB; a card needs neither, only one
 * licensed image and its credit. DETERMINISTIC (slugs sorted) so the sync guard
 * in check-guide-pick-photos.mjs is a plain equality check.
 *   hero = the guide's own reviewed hero (lib/guideHero.js)
 *   pick = the first curated pick photo (pick names sorted) in the manifest
 */
export function buildGuideCardPhotoIndex(manifest, heroArt) {
  const slim = (src, credit, href, position, kind) => (src ? { src, credit: credit || "", href: href || "", position: position || "50% 50%", ...(kind ? { kind } : {}) } : null);
  const slugs = [...new Set([...Object.keys(heroArt || {}), ...Object.keys(manifest || {})])].sort();
  const out = {};
  for (const slug of slugs) {
    const h = heroArt && heroArt[slug];
    const hero = h ? slim(h.src, h.credit, h.source, h.position, h.kind) : null;
    const picks = (manifest && manifest[slug] && manifest[slug].picks) || {};
    const first = Object.keys(picks).sort().map((k) => picks[k]).find((e) => e && e.src);
    const pick = first ? slim(first.src, first.credit, first.creditHref || first.sourceUrl, first.position) : null;
    if (hero || pick) out[slug] = { hero, pick };
  }
  return out;
}

export function renderCardIndexSource(index) {
  return `// GENERATED by scripts/build-guide-pick-photos.mjs — do not hand-edit.
// Slim slug -> { hero, pick } photo index for the guide card (see
// buildGuideCardPhotoIndex). Derived from lib/guideHero.js + the pick-photo
// manifest; scripts/check-guide-pick-photos.mjs fails when it is out of sync.
export const GUIDE_CARD_PHOTOS = ${JSON.stringify(index, null, 2)};
`;
}

async function main() {
  const files = loadGuidePickPhotoFiles();
  const data = buildGuidePickPhotos(files);
  writeFileSync(OUT_PATH, renderManifestSource(data));
  const { GUIDE_HERO_ART } = await import("../lib/guideHero.js");
  writeFileSync(CARD_INDEX_PATH, renderCardIndexSource(buildGuideCardPhotoIndex(data, GUIDE_HERO_ART)));
  const pickCount = Object.values(data).reduce((n, g) => n + Object.keys(g.picks || {}).length, 0);
  console.log(`build-guide-pick-photos: wrote ${Object.keys(data).length} guide(s), ${pickCount} pick photo(s) to lib/guidePickPhotoManifest.js`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
