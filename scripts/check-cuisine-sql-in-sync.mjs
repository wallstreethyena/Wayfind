#!/usr/bin/env node
/**
 * check-cuisine-sql-in-sync — the JS classifier and the SQL backfill must agree.
 *
 * The classifier has to exist twice: in JS because the cron runs it per row, and
 * in SQL because Supabase's legacy REST keys were disabled 2026-07-16, so the
 * batch over ~1,200 rows is a query rather than a fetch loop.
 *
 * Two hand-maintained copies of thirty regexes drift within a week, and the drift
 * is SILENT: both sides run, neither errors, and one quietly stops matching a
 * cuisine. So the SQL is GENERATED from the JS, and this guard re-generates and
 * diffs. A regex change that skips the migration fails the build.
 */
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";

let pass = 0;
const fail = [];
const ok = (c, m) => { if (c) pass++; else fail.push(m); };

const migPath = path.resolve("supabase/migrations/20260730_cuisine_backfill.sql");
const onDisk = readFileSync(migPath, "utf8");
const regenerated = execFileSync(process.execPath, [path.resolve("scripts/emit-cuisine-sql.mjs")], { encoding: "utf8" });

ok(onDisk.trim() === regenerated.trim(),
  "the generated backfill SQL is IN SYNC with lib/cuisine.js — run `node scripts/emit-cuisine-sql.mjs > supabase/migrations/20260730_cuisine_backfill.sql`");
ok(onDisk.includes("GENERATED by scripts/emit-cuisine-sql.mjs"), "the migration says it is generated, so nobody hand-edits it");
ok(regenerated.length > 3000, `the generator produced real SQL (${regenerated.length} chars) — an empty emit would trivially match an empty file`);
// The rule, restated where the SQL lives.
ok(/FILTER labels over local inventory, never query terms/.test(onDisk),
  "the generated SQL carries the filter-not-query rule");
// The live function in the database was installed from this same emit. Assert the
// distinctive parts are present so a partial paste is visible.
for (const marker of ["puerto[ -]?rican", "mofongo", "\\ykobe\\y", "nightclub"]) {
  ok(onDisk.includes(marker), `the SQL carries "${marker}" — the cases that motivated names and vetoes`);
}

if (fail.length) {
  console.error("check-cuisine-sql-in-sync: FAIL");
  for (const f of fail) console.error("  - " + f);
  process.exit(1);
}
console.log(`check-cuisine-sql-in-sync: OK — ${pass} assertions (regenerated and diffed against lib/cuisine.js)`);
