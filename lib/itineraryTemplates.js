export const SLOTS = Object.freeze(["morning", "midday", "afternoon", "evening", "night"]);
export const SLOT_LABEL = Object.freeze({ morning: "Morning", midday: "Midday", afternoon: "Afternoon", evening: "Evening", night: "Night" });
const MAX_PER_DAY = 5;
const MIN_TOTAL = 3;
const MAX_TOTAL = 10;

/** Higher is better: rating with a light editorial and photo preference. */
export function candidateRank(row) {
  const sig = row && row.signals && typeof row.signals === "object" ? row.signals : {};
  const rating = typeof sig.rating === "number" ? sig.rating : 0;
  const reviews = typeof sig.reviews === "number" ? sig.reviews : 0;
  return rating + (row.editorial ? 0.15 : 0) + (Array.isArray(sig.photo_gallery) && sig.photo_gallery.length ? 0.1 : 0) + Math.min(0.2, Math.log10(1 + reviews) / 20);
}

function placeFacts(r) {
  return cleanPublicText(r.editorial || (r.editorial_card && r.editorial_card.why) || "", 220);
}

/** Candidate list from inventory and event rows. Each gets a short id the model uses. */
export function buildCandidates(placeRows, eventRows, { todayStr, horizonStr } = {}) {
  const byCat = new Map();
  for (const r of placeRows || []) {
    if (!r || r.excluded === true) continue;
    if (String(r.status || "OPERATIONAL").toUpperCase() !== "OPERATIONAL") continue;
    const sig = r.signals && typeof r.signals === "object" ? r.signals : {};
    if (!(typeof sig.rating === "number" && sig.rating >= 4.4)) continue;
    const cat = String(r.category || "").toLowerCase();
    if (!["food", "attractions", "nightlife", "beach"].includes(cat)) continue;
    if (!byCat.has(cat)) byCat.set(cat, []);
    byCat.get(cat).push(r);
  }
  const quota = { food: 12, attractions: 10, nightlife: 6, beach: 4 };
  const out = [];
  for (const [cat, rows] of byCat) {
    rows.sort((a, b) => candidateRank(b) - candidateRank(a) || String(a.place_id).localeCompare(String(b.place_id)));
    for (const r of rows.slice(0, quota[cat] || 4)) {
      out.push({
        cid: "p" + (out.length + 1), kind: "place", ref_id: String(r.place_id), name: cleanPublicText(r.name, 90),
        category: cat, area: cleanPublicText(r.postal_city || r.locality || "", 60), facts: placeFacts(r),
        photo: openLicensePhoto(sig(r).photo_gallery),
      });
    }
  }
  for (const e of eventRows || []) {
    if (!e || !e.slug) continue;
    const st = String(e.event_status || "").toLowerCase();
    if (!["scheduled", "sold_out", ""].includes(st)) continue;
    const start = String(e.start_date || ""), end = String(e.end_date || e.start_date || "");
    if (todayStr && end && end < todayStr) continue;
    if (horizonStr && start && start > horizonStr) continue;
    const facts = cleanPublicText([e.why_go, e.editorial_summary, e.insider_tip].filter(Boolean).join(" "), 260);
    out.push({
      cid: "e" + (out.length + 1), kind: "event", ref_id: String(e.event_id || e.slug), slug: String(e.slug),
      name: cleanPublicText(e.event_name || e.short_title, 90), category: "event", area: cleanPublicText(e.city || "", 60),
      facts, start_date: start || null, end_date: end || null,
      time: typeof e.start_time === "string" && /^\d{2}:\d{2}/.test(e.start_time) ? e.start_time.slice(0, 5) : null,
      photo: null,
    });
    if (out.filter((c) => c.kind === "event").length >= 8) break;
  }
  return out.filter((c) => c.name);
}
function sig(r) { return r && r.signals && typeof r.signals === "object" ? r.signals : {}; }

export const TEMPLATE_SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["title", "intro", "days"],
  properties: {
    title: { type: "string" },
    intro: { type: "string" },
    days: {
      type: "array",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["day", "stops"],
        properties: {
          day: { type: "integer" },
          stops: {
            type: "array",
            items: {
              type: "object",
              additionalProperties: false,
              required: ["id", "slot", "why"],
              properties: { id: { type: "string" }, slot: { type: "string", enum: [...SLOTS] }, why: { type: "string" } },
            },
          },
        },
      },
    },
  },
};

export function templatePrompt(cands, { city, theme }) {
  const system = [
    "You plan Florida itineraries for Wayfind using ONLY the candidate stops given, by their id.",
    "Never add a place that is not in the list. Never invent hours, prices, dates or times.",
    `Plan ${theme.days} day(s) in ${city}. 3 to 5 stops a day, in a sensible order: morning food or coffee, daytime things to do, dinner, then a night spot if one fits.`,
    "Prefer stops in the same area on the same day. Use an event only on a day it is on.",
    "Each why: one sentence under 140 characters, from that stop's facts only. No dashes, no emojis, no links.",
    "Title under 60 characters, intro one sentence under 220 characters. Return JSON only.",
  ].join(" ");
  const user = JSON.stringify({
    city, days: theme.days,
    candidates: cands.map((c) => ({ id: c.cid, name: c.name, type: c.category, area: c.area, facts: c.facts, ...(c.kind === "event" ? { on: [c.start_date, c.end_date] } : {}) })),
  });
  return { system, user };
}

/** Keep only real candidates, valid slots, no repeats; null when the plan is too thin. */
export function validateTemplateReply(data, cands, theme) {
  if (!data || typeof data !== "object") return null;
  const byCid = new Map(cands.map((c) => [c.cid, c]));
  const used = new Set();
  const stops = [];
  for (const d of Array.isArray(data.days) ? data.days : []) {
    const day = Number(d && d.day);
    if (!Number.isInteger(day) || day < 1 || day > theme.days) continue;
    let n = 0;
    for (const s of Array.isArray(d.stops) ? d.stops : []) {
      const c = byCid.get(String(s && s.id || ""));
      if (!c || used.has(c.cid) || !SLOTS.includes(s.slot) || n >= MAX_PER_DAY) continue;
      used.add(c.cid);
      n += 1;
      stops.push({ c, day, slot: s.slot, why: cleanPublicText(s.why, 160) });
      if (stops.length >= MAX_TOTAL) break;
    }
  }
  if (stops.length < MIN_TOTAL) return null;
  stops.sort((a, b) => a.day - b.day || SLOTS.indexOf(a.slot) - SLOTS.indexOf(b.slot));
  const title = cleanPublicText(data.title, 80);
  return { title: title.length >= 3 ? title : null, intro: cleanPublicText(data.intro, 260), stops };
}

/** The plain rules planner: same candidates, fixed day shape. Always available. */
export function rulesPlan(cands, theme) {
  const pick = (cat, skip) => cands.find((c) => c.category === cat && !skip.has(c.cid));
  const used = new Set();
  const stops = [];
  for (let day = 1; day <= theme.days; day += 1) {
    const plan = [["food", "morning"], ["attractions", "midday"], ["beach", "afternoon"], ["food", "evening"], ["nightlife", "night"]];
    for (const [cat, slot] of plan) {
      const c = pick(cat, used) || (cat === "beach" ? pick("attractions", used) : null);
      if (!c) continue;
      used.add(c.cid);
      stops.push({ c, day, slot, why: c.facts || "" });
    }
  }
  return stops.length >= MIN_TOTAL ? { title: null, intro: "", stops } : null;
}

export function inputHash(cands, themeId) {
  return createHash("sha256").update(themeId + "|" + JSON.stringify(cands.map((c) => [c.cid, c.ref_id, c.facts]))).digest("hex");
}

export function templateRecord(plan, cands, { metro, city, theme, writer }) {
  const title = plan.title || `${theme.label} in ${city}`;
  const intro = plan.intro || `${plan.stops.length} Wayfind picks for ${theme.days > 1 ? `${theme.days} days` : "a day"} in ${city}, in a sensible order.`;
  const ends = plan.stops.filter((s) => s.c.kind === "event" && s.c.end_date).map((s) => s.c.end_date).sort();
  return {
    slug: `${slugify(city, 30)}-${slugify(theme.id.replace(/_/g, " "), 30)}`,
    metro, city, theme: theme.id, status: "published",
    title: cleanPublicText(title, 80), intro: cleanPublicText(intro, 300), days: theme.days,
    stops: plan.stops.map((s) => ({
      kind: s.c.kind, ref_id: s.c.ref_id, day: s.day, slot: s.slot, name: s.c.name, category: s.c.category, area: s.c.area,
      blurb: cleanPublicText(s.why || s.c.facts || "", 200), photo: s.c.photo || null,
      ...(s.c.kind === "event" ? { slug: s.c.slug, time: s.c.time, start_date: s.c.start_date, end_date: s.c.end_date } : {}),
    })),
    valid_until: ends[0] || null,
    input_hash: inputHash(cands, theme.id),
    writer,
    generated_at: new Date().toISOString(),
  };
}

/** Draft one template. Resolves a record ready to upsert, or null. */
export async function draftTemplate(cands, meta, deps = {}) {
  const json = deps.engineJson || engineJson;
  if (cands.filter((c) => c.kind === "place").length < MIN_TOTAL) return null;
  const { system, user } = templatePrompt(cands, meta);
  const r = await json({ system, user, schema: TEMPLATE_SCHEMA, schemaName: "itinerary_template", maxTokens: 1200 });
  const ai = r && r.ok ? validateTemplateReply(r.data, cands, meta.theme) : null;
  if (ai) return templateRecord(ai, cands, { ...meta, writer: "openai" });
  const rules = rulesPlan(cands, meta.theme);
  return rules ? templateRecord(rules, cands, { ...meta, writer: "rules" }) : null;
}

/** Template stops that are still on: events that ended are dropped at read time. */
export function liveStops(template, todayStr) {
  return (template.stops || []).filter((s) => s.kind !== "event" || !s.end_date || !todayStr || s.end_date >= todayStr);
}

// ── I/O ───────────────────────────────────────────────────────────────────
const svc = (cfg, extra = {}) => ({ apikey: cfg.service || cfg.key, Authorization: "Bearer " + (cfg.service || cfg.key), ...extra });
async function rjson(r) { try { return await r.json(); } catch { return null; } }

export async function loadCandidateRows(cfg, m, { todayStr, horizonStr }, fetchImpl = fetch) {
  const placeQ = `${cfg.url}/rest/v1/wf_inventory?metro=eq.${encodeURIComponent(m.metro)}&excluded=not.is.true&category=in.(food,attractions,nightlife,beach)&select=place_id,name,category,locality,postal_city,status,excluded,editorial,editorial_card,signals&order=signals->rating.desc.nullslast&limit=400`;
  const evQ = `${cfg.url}/rest/v1/wf_events?state=eq.FL&city=in.(${m.eventCities.map((c) => `"${c}"`).map(encodeURIComponent).join(",")})&end_date=gte.${todayStr}&start_date=lte.${horizonStr}&select=event_id,slug,event_name,short_title,city,event_status,start_date,end_date,start_time,why_go,editorial_summary,insider_tip&order=editorial_score.desc.nullslast&limit=20`;
  const [pr, er] = await Promise.all([fetchImpl(placeQ, { headers: svc(cfg), cache: "no-store" }), fetchImpl(evQ, { headers: svc(cfg), cache: "no-store" })]);
  if (!pr.ok) return null;
  return { places: (await rjson(pr)) || [], events: er.ok ? (await rjson(er)) || [] : [] };
}

export async function upsertTemplate(cfg, record, fetchImpl = fetch) {
  const r = await fetchImpl(`${cfg.url}/rest/v1/wf_itinerary_templates?on_conflict=metro,theme`, {
    method: "POST",
    headers: svc(cfg, { "content-type": "application/json", Prefer: "resolution=merge-duplicates,return=minimal" }),
    body: JSON.stringify(record),
    cache: "no-store",
  });
  return r.ok;
}

export async function listTemplates(cfg, fetchImpl = fetch) {
  if (!cfg) return [];
  const r = await fetchImpl(`${cfg.url}/rest/v1/wf_itinerary_templates?status=eq.published&select=slug,metro,city,theme,title,intro,days,stops,valid_until,writer,generated_at&order=metro.asc,theme.asc&limit=60`, { headers: svc(cfg), next: { revalidate: 600 } });
  if (!r.ok) return [];
  return (await rjson(r)) || [];
}

export async function readTemplate(cfg, slug, fetchImpl = fetch) {
  if (!cfg || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(String(slug || "")) || String(slug).length > 90) return null;
  const r = await fetchImpl(`${cfg.url}/rest/v1/wf_itinerary_templates?slug=eq.${slug}&status=eq.published&select=slug,metro,city,theme,title,intro,days,stops,valid_until,writer,generated_at&limit=1`, { headers: svc(cfg), next: { revalidate: 600 } });
  if (!r.ok) return null;
  return ((await rjson(r)) || [])[0] || null;
}
