// lib/itineraryTemplates.js — multi stop itinerary templates that OpenAI drafts
// from Wayfind's OWN data (owner order 2026-11-27).
//
// The "unstructured travel data" is what Wayfind already holds: the editorial
// lines on its places, and the why go, insider tip and summary text on its
// curated events. The model receives a numbered candidate list and may only
// arrange those candidates into a plan; it never names a place itself. The
// reply is checked against the exact ids sent, so an invented stop is dropped,
// and times are never written by the model: a stop shows a time only when the
// event row holds a real start time. Unknowns stay empty.
//
// Templates are regenerated by a twice daily cron (app/api/cron/itinerary-templates)
// for a fixed set of metros and themes, so the cost is bounded by the schedule
// (12 calls a week) and the engine's monthly dollar cap, not by traffic. If
// OpenAI is unavailable the plain rules planner below fills the same slots
// from the same candidates, so the page never goes empty.
