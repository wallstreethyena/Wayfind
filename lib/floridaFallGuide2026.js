function dedupeById(rows) {
  const seen = new Set();
  const out = [];
  for (const row of rows) {
    if (!row || !row.event_id || !row.event_name || seen.has(row.event_id)) continue;
    seen.add(row.event_id);
    out.push(row);
  }
  return out;
}

function sortByDate(a, b) {
  return String(a.start_date || "9999-12-31").localeCompare(String(b.start_date || "9999-12-31"))
    || String(a.event_name || "").localeCompare(String(b.event_name || ""));
}

