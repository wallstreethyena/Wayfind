export function fallGuideKind(event) {
  if (event?.guide_kind) return event.guide_kind;
  const text = [
    event?.event_name,
    event?.short_title,
    event?.subcategory,
    ...(Array.isArray(event?.tags) ? event.tags : []),
    ...(Array.isArray(event?.audience) ? event.audience : []),
  ].filter(Boolean).join(" ").toLowerCase();

  if (/trick|spooktacular|zoo boo|not so scary|brick or treat|goblins|trunk or treat|boo in bloom/.test(text)) return "family";
  if (/horror|haunt|scream|ghost|fear|nightmare|bar crawl|boos and booze/.test(text)) return "haunts";
  if (/oktoberfest|food|wine|coffee|cider|stone crab|pig jig|taste of the beach|seasonal menu/.test(text)) return "food";
  if (/pumpkin|farm|corn maze|harvest|sunflower|u-pick/.test(text)) return "farms";
  if (/fair|festival|craft|bayfest|foo foo|fantasy fest/.test(text)) return "festival";
  return "activities";
}

